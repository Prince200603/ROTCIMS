// =============================================================================
// FILE: nodescripts/generate_oauth_token.js
// PURPOSE: Automated Google OAuth 2.0 token generator for ROTCIMS.
//          Automatically locates and parses downloaded OAuth client JSON files,
//          launches the authorization flow, captures the offline refresh token,
//          updates .env.local securely, and displays Vercel environment variables.
//
// USAGE:
//   node nodescripts/generate_oauth_token.js
//   or specify JSON path:
//   node nodescripts/generate_oauth_token.js /path/to/client_secret.json
// =============================================================================

import { google } from 'googleapis';
import fs from 'fs';
import path from 'path';
import os from 'os';
import http from 'http';
import readline from 'readline';
import { exec } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PROJECT_ROOT = path.resolve(__dirname, '..');

const SCOPES = [
  'https://www.googleapis.com/auth/drive',
];

const DEFAULT_PORT = 8085;

/**
 * Scan directories to find the downloaded Google OAuth Client JSON file.
 */
function findOAuthClientFile(customPath) {
  if (customPath) {
    const resolved = path.resolve(customPath);
    if (fs.existsSync(resolved) && fs.statSync(resolved).isFile()) {
      return resolved;
    }
    console.error(`\n❌ Specified file not found: ${customPath}`);
  }

  const homedir = os.homedir();
  const candidateDirs = [
    path.join(homedir, 'storage', 'downloads'),
    '/storage/emulated/0/Download',
    '/sdcard/Download',
    path.join(homedir, 'downloads'),
    PROJECT_ROOT,
    path.join(PROJECT_ROOT, 'nodescripts'),
  ];

  const matchedFiles = [];

  for (const dir of candidateDirs) {
    if (!fs.existsSync(dir)) continue;
    try {
      const entries = fs.readdirSync(dir);
      for (const entry of entries) {
        if (!entry.endsWith('.json')) continue;
        const fullPath = path.join(dir, entry);
        try {
          const stat = fs.statSync(fullPath);
          if (!stat.isFile()) continue;

          // Quick inspect for OAuth credentials structure
          const raw = fs.readFileSync(fullPath, 'utf8');
          if (
            raw.includes('client_secret') &&
            (raw.includes('installed') || raw.includes('web') || raw.includes('client_id'))
          ) {
            const parsed = JSON.parse(raw);
            const clientData = parsed.installed || parsed.web || parsed;
            if (clientData && clientData.client_id && clientData.client_secret) {
              matchedFiles.push({
                filePath: fullPath,
                fileName: entry,
                dir,
                mtime: stat.mtimeMs,
                clientData,
              });
            }
          }
        } catch {
          // Ignore unreadable or non-JSON files
        }
      }
    } catch {
      // Ignore unreadable directories
    }
  }

  if (matchedFiles.length === 0) {
    return null;
  }

  // Sort descending by modified time (newest first)
  matchedFiles.sort((a, b) => b.mtime - a.mtime);
  return matchedFiles[0];
}

/**
 * Find an available local port starting from the given port.
 */
function findAvailablePort(startPort) {
  return new Promise((resolve) => {
    const server = http.createServer();
    server.listen(startPort, () => {
      server.close(() => resolve(startPort));
    });
    server.on('error', () => {
      resolve(findAvailablePort(startPort + 1));
    });
  });
}

/**
 * Safely update .env.local with OAuth credentials, preserving other settings.
 */
function saveToEnvLocal(clientId, clientSecret, refreshToken) {
  const envPath = path.join(PROJECT_ROOT, '.env.local');
  let content = '';
  if (fs.existsSync(envPath)) {
    content = fs.readFileSync(envPath, 'utf8');
  }

  // Remove existing occurrences
  content = content.replace(/^GOOGLE_CLIENT_ID=.*(?:\r?\n)?/gm, '');
  content = content.replace(/^GOOGLE_CLIENT_SECRET=.*(?:\r?\n)?/gm, '');
  content = content.replace(/^GOOGLE_REFRESH_TOKEN=.*(?:\r?\n)?/gm, '');

  if (content.length > 0 && !content.endsWith('\n')) {
    content += '\n';
  }

  content += '# Google Drive OAuth 2.0 (Generated by generate_oauth_token.js)\n';
  content += `GOOGLE_CLIENT_ID=${clientId}\n`;
  content += `GOOGLE_CLIENT_SECRET=${clientSecret}\n`;
  content += `GOOGLE_REFRESH_TOKEN=${refreshToken}\n`;

  fs.writeFileSync(envPath, content, { mode: 0o600 });
}

/**
 * Attempt to open URL in default Android / Linux browser
 */
function openBrowser(url) {
  // Try Termux open command first, then fallback to xdg-open
  exec(`termux-open-url "${url}" 2>/dev/null || xdg-open "${url}" 2>/dev/null`, () => {
    // Errors silently ignored; URL is already printed to console
  });
}

async function main() {
  console.log('\n╔══════════════════════════════════════════════════════════════╗');
  console.log('║        ROTCIMS — Google OAuth 2.0 Refresh Token Setup        ║');
  console.log('╚══════════════════════════════════════════════════════════════╝\n');

  // Step 1: Detect OAuth JSON
  const detected = findOAuthClientFile(process.argv[2]);
  if (!detected) {
    console.error('❌ Could not automatically locate Google OAuth Client JSON in:');
    console.error('   • ~/storage/downloads/');
    console.error('   • /storage/emulated/0/Download/');
    console.error('   • Current project directory');
    console.error('\nEnsure you downloaded the OAuth client JSON from Google Cloud Console:');
    console.error('  Google Cloud Console → APIs & Services → Credentials → OAuth 2.0 Client IDs → Download JSON');
    console.error('\nOr run with explicit path:');
    console.error('  node nodescripts/generate_oauth_token.js <path-to-client_secret.json>\n');
    process.exit(1);
  }

  const { clientData, filePath, fileName, mtime } = detected;
  const clientId = clientData.client_id;
  const clientSecret = clientData.client_secret;

  console.log(`📁 Located OAuth Client JSON:`);
  console.log(`   Path:     ${filePath}`);
  console.log(`   File:     ${fileName}`);
  console.log(`   Modified: ${new Date(mtime).toLocaleString()}`);
  console.log(`   Client:   ${clientId.slice(0, 16)}...apps.googleusercontent.com\n`);

  // Step 2: Configure Loopback Redirect Server
  const port = await findAvailablePort(DEFAULT_PORT);
  const redirectUri = `http://localhost:${port}`;
  const oauth2Client = new google.auth.OAuth2(clientId, clientSecret, redirectUri);

  const authUrl = oauth2Client.generateAuthUrl({
    access_type: 'offline', // Critical for getting a refresh token
    prompt: 'consent',      // Force consent to guarantee refresh_token is returned
    scope: SCOPES,
  });

  let isHandled = false;
  let server = null;
  let rl = null;

  async function handleAuthorizationCode(rawCode) {
    if (isHandled) return;
    isHandled = true;

    if (rl) {
      rl.close();
    }
    if (server) {
      try {
        server.close();
      } catch {}
    }

    try {
      let code = rawCode.trim();
      // Handle case where user pasted full redirect URL
      if (code.startsWith('http://') || code.startsWith('https://')) {
        try {
          const parsedUrl = new URL(code);
          code = parsedUrl.searchParams.get('code') || code;
        } catch {}
      }

      console.log('\n⏳ Exchanging authorization code with Google...');
      const { tokens } = await oauth2Client.getToken(code);
      const refreshToken = tokens.refresh_token;

      if (!refreshToken) {
        console.warn('\n⚠️  WARNING: Google did not return a "refresh_token".');
        console.warn('   This occurs if your Google account previously authorized this client.');
        console.warn('   To fix:');
        console.warn('   1. Visit: https://myaccount.google.com/connections');
        console.warn('   2. Select and remove ROTCIMS / OAuth client access.');
        console.warn('   3. Re-run this script to generate a fresh refresh token.\n');
      }

      // Save locally to .env.local
      saveToEnvLocal(clientId, clientSecret, refreshToken || 'FAILED_TO_OBTAIN');

      console.log('\n╔══════════════════════════════════════════════════════════════╗');
      console.log('║  ✅ SUCCESS! ROTCIMS GOOGLE OAUTH CREDENTIALS READY          ║');
      console.log('╚══════════════════════════════════════════════════════════════╝\n');
      console.log('Credentials saved to .env.local (file mode 0600).\n');
      console.log('─'.repeat(64));
      console.log('Add these 3 variables to Vercel Environment Variables:');
      console.log('─'.repeat(64));
      console.log(`GOOGLE_CLIENT_ID     = ${clientId}`);
      console.log(`GOOGLE_CLIENT_SECRET = ${clientSecret}`);
      console.log(`GOOGLE_REFRESH_TOKEN = ${refreshToken || '(Revoke access in Google Account and re-run)'}`);
      console.log('─'.repeat(64));
      console.log('\nNext steps:');
      console.log('1. Open Vercel Dashboard → Your Project → Settings → Environment Variables');
      console.log('2. Add or update GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET, and GOOGLE_REFRESH_TOKEN');
      console.log('3. Ensure GOOGLE_DRIVE_FOLDER_ID is set to your target Google Drive folder ID');
      console.log('4. Run "npm run test:drive" in Termux to test Drive authentication!\n');

      process.exit(0);
    } catch (err) {
      console.error('\n❌ Token exchange failed:', err.message);
      if (err.response && err.response.data) {
        console.error('Details:', JSON.stringify(err.response.data, null, 2));
      }
      process.exit(1);
    }
  }

  // Start temporary local loopback server to automatically capture the callback
  server = http.createServer((req, res) => {
    try {
      const parsedUrl = new URL(req.url, `http://localhost:${port}`);
      const code = parsedUrl.searchParams.get('code');
      const error = parsedUrl.searchParams.get('error');

      if (error) {
        res.writeHead(400, { 'Content-Type': 'text/html' });
        res.end(`
          <!DOCTYPE html>
          <html>
          <body style="font-family:sans-serif;background:#0f172a;color:#f87171;text-align:center;padding:50px;">
            <h2>Authorization Denied / Failed</h2>
            <p>Error: ${error}</p>
            <p>You can close this tab and return to Termux.</p>
          </body>
          </html>
        `);
        console.error(`\n❌ Authorization error received from Google: ${error}`);
        handleAuthorizationCode('');
        return;
      }

      if (code) {
        res.writeHead(200, { 'Content-Type': 'text/html' });
        res.end(`
          <!DOCTYPE html>
          <html>
          <head>
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>ROTCIMS - Google OAuth Success</title>
            <style>
              body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #0f172a; color: #f8fafc; display: flex; align-items: center; justify-content: center; height: 100vh; margin: 0; padding: 20px; box-sizing: border-box; text-align: center; }
              .card { background: #1e293b; border-radius: 14px; padding: 36px 24px; max-width: 440px; border: 1px solid #334155; box-shadow: 0 10px 25px rgba(0,0,0,0.5); }
              h1 { color: #22c55e; margin: 12px 0; font-size: 22px; }
              p { color: #94a3b8; font-size: 15px; line-height: 1.5; margin-bottom: 24px; }
              .badge { display: inline-block; background: #22c55e20; color: #4ade80; border: 1px solid #22c55e40; padding: 8px 16px; border-radius: 999px; font-size: 14px; font-weight: 600; }
            </style>
          </head>
          <body>
            <div class="card">
              <div style="font-size: 48px;">✅</div>
              <h1>ROTCIMS Authorization Complete</h1>
              <p>Your Google Drive authorization code has been received. Token generation is proceeding in Termux.</p>
              <div class="badge">You can close this tab and return to Termux</div>
            </div>
          </body>
          </html>
        `);
        handleAuthorizationCode(code);
      } else {
        res.writeHead(404);
        res.end();
      }
    } catch (err) {
      console.error('Error handling redirect:', err.message);
    }
  });

  await new Promise((resolve) => {
    server.listen(port, () => {
      console.log(`🌐 Local loopback listener active on port ${port}.\n`);
      resolve();
    });
  });

  console.log('─'.repeat(64));
  console.log('Step 1: Open this Authorization URL in Chrome:\n');
  console.log(authUrl);
  console.log('\n' + '─'.repeat(64));
  console.log('Step 2: Sign in with the Google Account that manages ROTCIMS Drive files.');
  console.log('Step 3: Click "Allow" to grant Google Drive file permissions.');
  console.log('\nℹ️  ANDROID CHROME NOTE:');
  console.log('   When Google finishes, Chrome may say "This site can\'t be reached"');
  console.log('   at http://localhost:8085. THIS IS NORMAL on Android sandboxing.');
  console.log('   Simply tap Chrome\'s address/URL bar, COPY the full URL:');
  console.log('   (e.g. http://localhost:8085/?code=4/0A...&scope=...)');
  console.log('   and PASTE it below!');
  console.log('─'.repeat(64) + '\n');

  // Attempt automatic browser launch
  openBrowser(authUrl);

  // Setup manual input fallback in case local redirect is not reachable
  rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  rl.question('Paste the authorization code or full Chrome address URL here: ', (input) => {
    if (input && input.trim()) {
      handleAuthorizationCode(input.trim());
    }
  });
}

main().catch((err) => {
  console.error('\n❌ Unexpected error:', err);
  process.exit(1);
});
